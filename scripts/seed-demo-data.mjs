#!/usr/bin/env node
/**
 * Demo history generator — DEV / DEMO ONLY.
 *
 * Real reach and engagement come from social platforms once live publishing
 * exists. Until then, this script gives a business a believable past so Home
 * and Analytics have something to show:
 *
 *   - ~8 weeks of backdated, PUBLISHED campaigns using the business's own
 *     products (1–3 platforms each), and
 *   - post_metrics rows for each of those posts, with a few built-in
 *     patterns (one standout product, Friday/Saturday evenings do better,
 *     reach trends upward) so the insights have something to find.
 *
 * Demo campaigns are tagged (instructions = DEMO_TAG) so --reset removes
 * exactly what this script created and nothing else.
 *
 * Usage:
 *   npm run seed:demo -- --email owner@example.com            # add demo history
 *   npm run seed:demo -- --email owner@example.com --reset    # remove it
 *   npm run seed:demo -- --list                               # list businesses
 *
 * Uses SUPABASE_SECRET_KEY (bypasses RLS) from .env.local or .env.
 */

import { existsSync, readFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const DEMO_TAG = "[Demo history — generated by scripts/seed-demo-data.mjs]";
const MANILA_OFFSET_HOURS = 8;

// ─── env & args ─────────────────────────────────────────────────────────────

function loadEnv() {
  const env = { ...process.env };
  for (const file of [".env", ".env.local"]) {
    if (!existsSync(file)) continue;
    for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
  return env;
}

function parseArgs(argv) {
  const args = { campaigns: 16, weeks: 8 };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--email") args.email = argv[++i];
    else if (a === "--business") args.business = argv[++i];
    else if (a === "--campaigns") args.campaigns = Number(argv[++i]);
    else if (a === "--weeks") args.weeks = Number(argv[++i]);
    else if (a === "--reset") args.reset = true;
    else if (a === "--list") args.list = true;
    else throw new Error(`Unknown argument: ${a}`);
  }
  return args;
}

function fail(message) {
  console.error(`\n✗ ${message}\n`);
  process.exit(1);
}

// ─── deterministic randomness (same business → same history) ────────────────

function seededRandom(seedText) {
  let h = 1779033703 ^ seedText.length;
  for (let i = 0; i < seedText.length; i++) {
    h = Math.imul(h ^ seedText.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return () => {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    return ((h ^= h >>> 16) >>> 0) / 4294967296;
  };
}

// ─── main ───────────────────────────────────────────────────────────────────

const env = loadEnv();
const args = parseArgs(process.argv.slice(2));
if (!env.NEXT_PUBLIC_SUPABASE_URL || !env.SUPABASE_SECRET_KEY) {
  fail("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SECRET_KEY must be set in .env.local or .env.");
}

const db = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SECRET_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

async function must(promise, what) {
  const { data, error } = await promise;
  if (error) fail(`${what}: ${error.message}`);
  return data;
}

async function listBusinesses() {
  const [businesses, { users }] = await Promise.all([
    must(db.from("businesses").select("id, name, owner_id"), "Loading businesses"),
    must(db.auth.admin.listUsers({ perPage: 1000 }), "Loading users"),
  ]);
  const emailById = new Map(users.map((u) => [u.id, u.email]));
  return businesses.map((b) => ({ ...b, email: emailById.get(b.owner_id) ?? "?" }));
}

async function resolveBusiness() {
  const all = await listBusinesses();
  let matches = all;
  if (args.business) matches = all.filter((b) => b.id === args.business);
  else if (args.email) matches = all.filter((b) => b.email?.toLowerCase() === args.email.toLowerCase());

  if (matches.length === 1) return matches[0];
  if (matches.length === 0) fail("No matching business. Run with --list to see them.");
  fail("More than one business matches. Pass --email <owner email> or --business <id>.");
}

async function reset(business) {
  const demo = await must(
    db.from("campaigns").select("id").eq("business_id", business.id).eq("instructions", DEMO_TAG),
    "Finding demo campaigns"
  );
  if (demo.length === 0) {
    console.log(`No demo history found for "${business.name}".`);
    return;
  }
  // Posts and metrics cascade with the campaign.
  await must(db.from("campaigns").delete().in("id", demo.map((c) => c.id)), "Deleting demo campaigns");
  console.log(`✓ Removed ${demo.length} demo campaigns (and their posts and metrics) from "${business.name}".`);
}

const GOALS = [
  ["PROMOTE_PRODUCT", "Promote a product"],
  ["GET_MORE_ORDERS", "Get more orders"],
  ["PROMOTION", "Promote a discount"],
  ["GET_STORE_VISITS", "Get more store visits"],
  ["KEEP_PAGE_ACTIVE", "Keep my page active"],
];

// Manila weekday (0 = Sunday) + hour, with how well that slot tends to do.
const SLOTS = [
  { day: 5, hour: 18, boost: 1.35 }, // Friday evening
  { day: 6, hour: 17, boost: 1.25 }, // Saturday evening
  { day: 3, hour: 12, boost: 0.95 }, // Wednesday midday
  { day: 1, hour: 8, boost: 0.8 },   // Monday morning
  { day: 0, hour: 10, boost: 1.0 },  // Sunday morning
  { day: 2, hour: 19, boost: 1.05 }, // Tuesday evening
];

const PLATFORM_BASE = { FACEBOOK: 900, INSTAGRAM: 1300, TIKTOK: 2100 };

async function seed(business) {
  const existing = await must(
    db.from("campaigns").select("id", { count: "exact", head: false })
      .eq("business_id", business.id).eq("instructions", DEMO_TAG),
    "Checking existing demo data"
  );
  if (existing.length > 0) {
    fail(`"${business.name}" already has demo history. Run with --reset first to regenerate it.`);
  }

  const products = await must(
    db.from("products").select("id, name, price, promo_price, description, image_url")
      .eq("business_id", business.id).eq("availability", "ACTIVE")
      .order("created_at"),
    "Loading products"
  );
  if (products.length === 0) fail(`"${business.name}" has no available products. Add some in the app first.`);

  const rand = seededRandom(business.id);
  const pick = (list) => list[Math.floor(rand() * list.length)];
  // One product quietly outperforms the rest, so there's a clear "best product".
  const star = products[Math.floor(rand() * products.length)];
  const productBoost = new Map(products.map((p) => [p.id, p.id === star.id ? 1.45 : 0.8 + rand() * 0.3]));

  const now = new Date();
  const days = args.weeks * 7;
  let postCount = 0;

  for (let i = 0; i < args.campaigns; i++) {
    // Spread campaigns across the window, oldest first; snap to a posting slot.
    const daysAgo = Math.max(1, Math.round(days - (i + 0.5) * (days / args.campaigns)));
    const slot = pick(SLOTS);
    const manilaNow = new Date(now.getTime() + MANILA_OFFSET_HOURS * 3600e3);
    const target = new Date(Date.UTC(
      manilaNow.getUTCFullYear(), manilaNow.getUTCMonth(), manilaNow.getUTCDate() - daysAgo,
      slot.hour - MANILA_OFFSET_HOURS, 0, 0
    ));
    // Move back to the slot's weekday (Manila) without going into the future.
    const manilaDay = new Date(target.getTime() + MANILA_OFFSET_HOURS * 3600e3).getUTCDay();
    target.setUTCDate(target.getUTCDate() - ((manilaDay - slot.day + 7) % 7));
    if (target >= now) continue;

    const product = i < products.length ? products[i] : pick(products);
    const [goal, goalLabel] = GOALS[i % GOALS.length];
    const platforms = ["FACEBOOK", "INSTAGRAM", ...(rand() < 0.45 ? ["TIKTOK"] : [])]
      .filter((p) => p !== "FACEBOOK" || rand() < 0.85);
    const price = `₱${Number(product.promo_price ?? product.price).toLocaleString("en-PH")}`;

    const campaign = await must(
      db.from("campaigns").insert({
        business_id: business.id,
        product_id: product.id,
        goal,
        promotion: goal === "PROMOTION" ? "10% off this weekend" : null,
        instructions: DEMO_TAG,
      }).select("id").single(),
      "Creating demo campaign"
    );

    const publishedAt = target.toISOString();
    const posts = await must(
      db.from("social_posts").insert(platforms.map((platform) => ({
        campaign_id: campaign.id,
        product_id: product.id,
        platform,
        title: `${product.name} · ${goalLabel}`,
        caption: `${product.name} for ${price}. ${product.description ?? ""}`.trim(),
        media_url: product.image_url || null,
        scheduled_at: publishedAt,
        published_at: publishedAt,
        status: "PUBLISHED",
      }))).select("id, platform"),
      "Creating demo posts"
    );

    // Older posts reach fewer people; recent ones more (a gentle upward trend).
    const trend = 0.7 + 0.6 * ((days - daysAgo) / days);
    const metrics = posts.map((post) => {
      const noise = 0.8 + rand() * 0.4;
      const reach = Math.round(PLATFORM_BASE[post.platform] * productBoost.get(product.id) * slot.boost * trend * noise);
      const engagement = post.platform === "TIKTOK" ? 0.11 : post.platform === "INSTAGRAM" ? 0.09 : 0.06;
      return {
        post_id: post.id,
        reach,
        impressions: Math.round(reach * (1.3 + rand() * 0.3)),
        views: post.platform === "TIKTOK" ? Math.round(reach * 1.8) : 0,
        likes: Math.round(reach * engagement * 0.7),
        comments: Math.round(reach * engagement * 0.12),
        shares: Math.round(reach * engagement * 0.1),
        saves: Math.round(reach * engagement * (post.platform === "INSTAGRAM" ? 0.15 : 0.05)),
        clicks: Math.round(reach * (post.platform === "FACEBOOK" ? 0.03 : 0.015)),
        watch_time: post.platform === "TIKTOK" ? Math.round(reach * 6) : null,
        collected_at: new Date(target.getTime() + 2 * 86400e3).toISOString(),
      };
    });
    await must(db.from("post_metrics").insert(metrics), "Creating demo metrics");
    postCount += posts.length;
  }

  console.log(
    `✓ Added demo history to "${business.name}": ${postCount} published posts over ${args.weeks} weeks.` +
    `\n  Standout product: ${star.name}. Remove it any time with --reset.`
  );
}

if (args.list) {
  const all = await listBusinesses();
  if (all.length === 0) console.log("No businesses yet — sign up in the app first.");
  for (const b of all) console.log(`${b.id}  ${b.email}  ${b.name}`);
} else {
  const business = await resolveBusiness();
  await (args.reset ? reset(business) : seed(business));
}
